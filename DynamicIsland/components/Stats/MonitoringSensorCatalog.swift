struct MonitoringSensorDefinition: Sendable {
    var key: String
    var name: String
    var group: String
    var unit: MonitoringUnit
    var platforms: String
    func supports(_ platform: String) -> Bool {
        platforms.split(separator: " ").contains { token in
            token == "all" || token.lowercased() == platform.lowercased() ||
                (token.hasSuffix("Gen") && platform.lowercased().hasPrefix(token.dropLast(3).lowercased()))
        }
    }
}

